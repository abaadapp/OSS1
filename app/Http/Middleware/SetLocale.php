<?php

namespace App\Http\Middleware;

use App\Models\Setting;
use App\Support\Tenancy;
use Closure;
use Illuminate\Http\Request;

/**
 * يضبط لغة الواجهة لكل طلب، بأولوية من الأخصّ إلى الأعمّ:
 *
 *   1. الجلسة        — اختيار هذه الجلسة (يشمل الزائر قبل الدخول)
 *   2. المستخدم      — تفضيله الشخصي الباقي بعد الخروج
 *   3. إعداد النشاط  — افتراضي المتجر لمن لم يختر بعد
 *   4. إعداد المنصة  — افتراضي المنصّة كلّها لمن لا نشاط له ولمن لم يُضبط نشاطه
 *   5. العربية
 *
 * الخطوة 2 هي الجديدة: بدونها كان الكاشير والمالك يتنازعان إعدادًا واحدًا
 * مشتركًا، فيغيّر كلٌّ منهما لغة الآخر.
 *
 * ═══ والخطوة 4 كانت مفقودةً من السلسلة ═══
 *
 * «اللغة الافتراضية» في إعدادات المنصّة حقلٌ يختاره المشغّل ويُحفظ في
 * `settings[null,'locale']` — **ولا يقرؤه سطرٌ في النظام كلِّه**. وشاشتُه
 * تَعِد بما لا يقع، بنصٍّ مكتوبٍ فيها: «لغة المنصة لمن لم يختر بعد».
 *
 * فالمشغّل يختار الإنجليزية ويحفظ ويقرأ «تم الحفظ»، وتبقى الواجهة عربيّةً
 * له ولكلّ من لا تفضيلَ له إلى الأبد. ولا رسالةَ عطبٍ تدلّه — مقبضٌ لا
 * يُدير شيئًا، وهو أسوأ من غيابه لأنّه يُطمئن.
 *
 * وموضعُه هنا بعد النشاط لا قبله: الأخصُّ يغلب. متجرٌ ضبط لغته لا تُبدّلها
 * المنصّة عليه.
 */
class SetLocale
{
    public const SUPPORTED = ['ar', 'en'];

    public function handle(Request $request, Closure $next)
    {
        $locale = session('locale');
        $user = auth()->user();

        if (! in_array($locale, self::SUPPORTED, true) && $user) {
            $locale = $user->locale;
        }

        if (! in_array($locale, self::SUPPORTED, true) && $user && $user->business_id) {
            $locale = Setting::where('business_id', $user->business_id)
                ->where('key', 'locale')->value('value');
        }

        /*
         * لغةُ المنصّة — «لمن لم يختر بعد» كما تقول شاشتُها.
         *
         * وتُقرأ داخل حارس: هذا الوسيط يجري على **كلّ** طلبٍ في التطبيق، بما
         * فيه أوّلُ طلبٍ على تنصيبٍ جديد قبل أن تُهاجَر القاعدة — ولا جدولَ
         * `settings` بعد. واستعلامٌ يسقط هنا يجعل كلّ صفحةٍ خمسمئة، وأوّلَ ما
         * يراه المنصِّب صفحةَ عطبٍ لا صفحةَ دخول.
         *
         * ولا يُبتلع خطأٌ حقيقيّ بهذا: قاعدةٌ بلا جدول إعداداتٍ يفضحها كلُّ
         * ما سواها. واللغةُ آخرُ ما يجوز أن يُسقط صفحة — تحتها العربية دائمًا.
         */
        if (! in_array($locale, self::SUPPORTED, true)) {
            try {
                $locale = Tenancy::platform('locale');
            } catch (\Throwable) {
                $locale = null;
            }
        }

        if (! in_array($locale, self::SUPPORTED, true)) {
            $locale = 'ar';
        }

        app()->setLocale($locale);

        // Carbon لا يتبع لغة التطبيق تلقائيًا — بدون هذا تبقى «منذ 19 دقيقة»
        // وأسماء الشهور عربية في الواجهة الإنجليزية.
        \Carbon\Carbon::setLocale($locale);

        return $next($request);
    }
}
