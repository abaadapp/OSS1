    /** @return array<int, array{0: string, 1: string, 2: string}> */
    /**
     * وجهُ كلّ نوعٍ في الشاشة — رمزٌ وسطرٌ يقول ما الذي يُدار به.
     *
     * ═══ ولمَ هنا لا في شاشة التسجيل ═══
     *
     * النوعُ يُغيّر تصنيفاتِ البداية المبذورة، وهي في هذا الملفّ. فقائمةٌ
     * ثانيةٌ في الواجهة تفترق عنه عند أوّل نوعٍ يُضاف: يُعرض على المسجِّل
     * نوعٌ لا يعرفه `provision` فيفتح لوحتَه على تصنيفاتٍ عامّة، أو يُبذَر
     * نوعٌ لا يراه أحد.
     *
     * والوصفُ ما يُدار فعلًا في النظام لكلٍّ — لا وعدًا بميزةٍ ليست فيه.
     */
    private const FACES = [
        'محل ورود' => ['🌷', 'باقات ومناسبات وهدايا — بالطلبات والمخزون والعملاء'],
        'مطعم' => ['🍽️', 'أطباق وأقسام — بالطلبات ونقطة البيع والمخزون'],
        'كافيه' => ['☕', 'مشروبات وحلويات — ببيعٍ سريع وإيصالٍ يُطبع'],
        'بقالة' => ['🛒', 'أصناف وكميّات — بالباركود والجرد والمشتريات'],
        'صيدلية' => ['💊', 'أدوية ومستلزمات — بالمخزون والصلاحيات والتقارير'],
        'متجر ملابس' => ['👗', 'مقاسات وأقسام — بالمخزون والمبيعات والمتجر الإلكتروني'],
    ];

    /**
     * الأنواعُ كما تُعرض على من يسجّل — من السجلّ نفسِه لا من قائمةٍ تُكتب.
     *
     * @return list<array{value: string, label: string, icon: string, hint: string}>
     */
    public static function options(): array
    {
        return array_map(fn (string $type) => [
            'value' => $type,
            'label' => __($type),
            'icon' => self::FACES[$type][0] ?? '🏪',
            'hint' => __(self::FACES[$type][1] ?? ''),
        ], self::TYPES);
    }

    public static function starterCategories(string $type): array
    {
        return self::STARTER[$type] ?? self::GENERIC;
    }

    /**
     * يزرع تصنيفات البداية للمتجر. لا يفعل شيئًا إن كان للمتجر تصنيف واحد
     * على الأقل — كي لا يعيد التعديلُ على متجر قائم زرعَ ما حذفه صاحبه.
     *
     * @return int عدد التصنيفات المزروعة
     */
    public static function provision(Business $business): int
    {
        if (Category::where('business_id', $business->id)->exists()) {
            return 0;
        }

        foreach (self::starterCategories($business->type) as [$name, $icon, $color]) {
            Category::create([
                'business_id' => $business->id,
                'name' => $name,
                'icon' => $icon,
                'color' => $color,
            ]);
        }

        return count(self::starterCategories($business->type));
    }
}
