     * يُحوَّل بمعامل شاشةٍ لا معنى له على ورق.
     *
     * والسلّمُ نسبيٌّ لا أرقامٌ متفرّقة: كلُّ مقاسٍ يضربه معاملُ الخطّ الذي
     * اختاره التاجر، فتكبر الورقةُ معًا ولا يكبر سطرُ الجسد وحده.
     */
    public const GEOMETRY = [
