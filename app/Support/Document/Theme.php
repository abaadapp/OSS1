         */
        'radius' => 3.0,
        'radius_lg' => 6.0,
        // ارتفاعُ الغلاف: يكفي ليُرى ولا يأكل ثلثَ الورقة
        'cover_height' => 108.0,
        'logo_height' => 40.0,
        /*
         * ═══ سلّمُ الخطّ — أربعُ درجاتٍ مقروءةٌ من المرجع نفسِه ═══
         *
         * فُكَّ مجرى محتوى المرجع وعُدَّت أوامرُ `Tf` فيه، فإذا مقاساتُه
         * أربعةٌ لا غير على ورقة A4 قياسُها ٥٩٥٫٩×٨٤١٫٩ نقطة:
         *
         *     ١٠pt   ×٨    التذييل
         *     ١٢pt   ×١٥١  الجسدُ كلُّه — التسمياتُ والقيمُ وخلايا الجدول
         *     ١٤pt   ×٦    العملةُ بجانب الرقم الكبير
         *     ٢٨٫٨pt ×١١   عنوانُ المستند والرقمُ الأهمّ
         *
         * ═══ وكانت هذه الأرقامُ مضروبةً بمعاملٍ لا موضعَ له ═══
         *
         * قُرئ من مصفوفة التحويل معاملٌ مقدارُه ٠٫٧٤١٧٦ وضُرب في مقاسات
         * الخطّ وحدَها: ٢٨٫٨ صارت ٢١٫٤، و١٤ صارت ١٠٫٤، و١٢ صارت ٨٫٩ ثمّ
         * رُفعت إلى ١٠ لتُقرأ. وبقيت الهندسةُ — خطوةُ السطر ١٣٫٤ والفراغُ
         * بين الحقول ٢٠٫٧ وارتفاعُ الصفّ ٢١٫٥ — بأرقامها كما قِيست.
         *
         * فخرجت ورقةٌ نصفُها بمقياسٍ ونصفُها بآخر: خطٌّ عند ثلاثة أرباعه
         * وفراغٌ عند تمامه. وهذا بعينه ما يجعل المستندَ يُقرأ **مصغَّرًا**
         * على A4 — لا صِغَرُ الخطّ وحدَه، بل خطٌّ صغيرٌ في فراغٍ كبير.
         *
         * و`Tf` مقاسٌ بالنقطة على الورقة مباشرةً حين تكون المصفوفةُ
         * `1 0 0 -1` — وهي كذلك في المرجع. فلا معاملَ يُضرب، وهذه هي
