<?php

namespace App\Support\Document;

/**
 * نسخةُ القالب الذي رُسمت به ورقةٌ — لا القالبُ الذي نرسم به اليوم.
 *
 * ═══ المشكلة التي يحلّها ═══
 *
 * الفاتورةُ مستندٌ محاسبيّ. تُصدَر، وتُرسَل، وتُطبع، ويحتفظ بها المشتري
 * والبائع والمدقّق. وبعد سنةٍ يُطلب من التاجر أن يُخرج نسخةً منها.
 *
 * وبلا هذا الملفّ: يفتحها فيجدها **بالشكل الجديد** — لأنّ القالبَ تغيّر
 * وهي تُرسم بقالب اليوم. فالورقةُ التي في يد المدقّق والورقةُ التي في
 * النظام ليستا الورقةَ نفسَها، ولا سطرَ يقول أيُّهما الأصل. وإن كان
 * التاجرُ قد بدّل لونَه بينهما فالفرقُ يُرى بالعين.
 *
 * ═══ والحلُّ لقطةٌ صغيرة لا نسخةُ HTML ═══
 *
 * لا يُخزَّن رسمُ الورقة كاملًا: ميغابايتٌ لكلّ فاتورةٍ في متجرٍ يبيع مئةً
 * في اليوم، وسجلٌّ لا يُبحث فيه ولا يُصلَح إن انكشف فيه عطب.
 *
 * ويُخزَّن **اسمُ القالب وهويّةُ اللحظة**: أيُّ قالبٍ رسمها، وبأيّ لونٍ
 * وشعارٍ وغلاف. فتُعاد بناءً لا استرجاعًا — وهو ما يجعلها قابلةً للإصلاح
 * إن ظهر في القالب عطبٌ يمسّ الأوراقَ كلَّها.
 *
 * ═══ ومتى تُلتقط ═══
 *
 * عند **الإصدار** لا عند الطباعة: مسودّةٌ تُطبع للمراجعة لا تُثبّت شيئًا،
 * وطباعةٌ ثانيةٌ لفاتورةٍ صدرت يجب أن تُخرج ما أُخرج أوّلَ مرّة.
 */
class Version
{
    /** القالبُ الذي يُرسم به اليوم */
    public const CURRENT = 'eventplus-modern-v1';

    /**
     * القوالبُ المعروفة — ولكلٍّ منها مجلَّدُ رسمه.
     *
     * وتبقى النسخةُ القديمة في المستودع بعد أن تُستبدل: حذفُها يجعل كلَّ
     * ورقةٍ تحمل اسمَها تسقط إلى `CURRENT` بلا أن يقول ذلك أحد — وهو
     * بالضبط ما يمنعه هذا الملفّ.
     */
    public const KNOWN = [
        'eventplus-modern-v1' => 'documents.v1',
    ];

    /** مجلَّدُ رسمِ نسخةٍ — والمجهولةُ تُرسم بالحاليّ لا تسقط */
    public static function views(?string $version): string
    {
        return self::KNOWN[$version ?? ''] ?? self::KNOWN[self::CURRENT];
    }

    /** أهذه نسخةٌ نعرفها؟ */
    public static function known(?string $version): bool
    {
        return $version !== null && array_key_exists($version, self::KNOWN);
    }

    /**
     * لقطةُ الهويّة كما هي الآن — تُحفظ مع المستند عند إصداره.
     *
     * والشعارُ والغلافُ **مساران** لا صورتان مضمَّنتان: الصورةُ المرمَّزة
     * تضخّم الصفَّ إلى ميغابايت، وملفُّ الشعار نفسُه لا يتغيّر حين يبدّل
     * التاجر لونَه. ومن بدّل شعارَه فعلًا يرفع ملفًّا جديدًا بمسارٍ جديد،
     * فيبقى القديمُ حيث هو وتقرؤه ورقتُه القديمة.
     *
     * @return array<string, string>
     */
    public static function snapshot(int $businessId): array
    {
        $brand = Branding::brand($businessId);

        return [
            'template' => self::CURRENT,
            'primary' => $brand['primary'],
            'accent' => $brand['accent'],
            'logo' => Branding::logoPath($businessId) ?? '',
            'cover' => Branding::coverPath($businessId) ?? '',
        ];
    }
}
