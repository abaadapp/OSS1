<?php

namespace App\Support;

/**
 * ما يراه الكاشير من سجلّ الفواتير.
 *
 * الشاشة كانت تُرسل آخر ثلاثين فاتورة بمبالغها كاملة إلى كل من يفتحها،
 * والبحث فيها يتجاوز الثلاثين إلى تاريخ الفرع كلّه. فأي كاشير يجمع عمودًا
 * واحدًا فيعرف حصيلة اليوم وكم باع كل زميل.
 *
 * والحلّ ليس إخفاء العمود في الواجهة: الأرقام تبقى في الاستجابة، ومن يفتح
 * أدوات المتصفّح يقرؤها كما هي — منعٌ يبدو منعًا وليس بمنع. لذلك تُنزع
 * المبالغ من الحمولة نفسها، ويبقى ما تحتاجه المهمّة اليومية: إيجاد فاتورة
 * زبون بالرقم أو بالاسم عند الإرجاع.
 *
 * فاتورةٌ واحدة تُفتح بتفاصيلها كاملة عبر pos.receipts.show — لأن الزبون
 * يستلمها مطبوعة على أي حال. الممنوع هو الاطّلاع بالجملة لا الفاتورة.
 */
class ReceiptVisibility
{
    /** المبالغ التي تُنزع من صفوف القائمة */
    private const MONEY = ['total', 'subtotal', 'discount', 'tax', 'delivery_fee', 'lines'];

    /**
     * صلاحية `finance` هي نفسها التي تحرس شاشة المدفوعات — فمن يرى حصيلة
     * الصندوق يرى مبالغ الفواتير، ومن لا يراها لا يراها في الشاشتين معًا.
     */
    public static function showsAmounts(): bool
    {
        $user = auth()->user();

        return $user !== null && $user->allows('finance');
    }

    /** يُمرّر الصفوف كما هي لمن يملك الصلاحية، ويُجرّدها من المبالغ لغيره */
    public static function filter(array $rows): array
    {
        if (self::showsAmounts()) {
            return $rows;
        }

        return array_map(
            fn (array $r) => array_diff_key($r, array_flip(self::MONEY)),
            $rows,
        );
    }
}
