<?php

namespace App\Support;

use App\Models\Business;
use App\Models\PurchaseOrder;
use App\Models\Setting;
use App\Models\Supplier;
use Illuminate\Support\Facades\DB;

/**
 * أمرُ الشراء — حالاتُه ورقمُه.
 *
 * ═══ وهو نيّةٌ لا حدث ═══
 *
 * لا يزيد رصيدًا ولا يُنشئ ذمّةً ولا يكتب قيدًا. البضاعةُ تدخل الرفَّ
 * باعتماد الاستلام، والذمّةُ تنشأ باعتماد سند المورّد — وهذا الملفّ لا
 * يمسّ أيًّا منهما.
 *
 * ═══ والحالاتُ الأربع كما هي في القاعدة ═══
 *
 * «مسودة» افتراضُ العمود منذ أوّل هجرة، و«مُرسل» ما كان يُكتب عند الإنشاء،
 * و«مستلم جزئيًا» و«مستلم» يكتبهما `GoodsReceipts::approve`. فلا حالةَ
 * تُخترع هنا: تُسمّى القائمةُ فقط لتُقرأ في موضعٍ واحد.
 */
final class PurchaseOrders
{
    /**
     * لم يُرسل بعد — ويُحذف ما لم يقع عليه شيء.
     *
     * ولا بابَ ينقله إلى «مُرسل» ولا بابَ يعدّله: الحالةُ تُكتب مرّةً عند
     * الإنشاء (`draft` في الطلب)، وما عداها يكتبه اعتمادُ الاستلام. فالاستلامُ
     * عليه مقبول — ولو مُنع لبقيت المسودّةُ بابًا لا يُخرج منه شيء.
     */
    public const DRAFT = 'مسودة';

    /** أُرسل إلى المورّد وينتظر شحنته */
    public const SENT = 'مُرسل';

    public const PARTIAL = 'مستلم جزئيًا';

    public const RECEIVED = 'مستلم';

    /**
     * ═══ وسائلُ السداد المنويّة — نيّةٌ لا حدث ═══
     *
     * هذه ما يُختار على **أمر الشراء**: كيف اتّفق التاجرُ مع مورّده أن
     * يسدّد. ولا واحدةٌ منها تكتب قيدًا ولا تُنقص صندوقًا ولا تُنشئ ذمّة —
     * الذمّةُ تنشأ باعتماد سند المورّد، والمالُ يخرج بالسداد على السند.
     *
     * ═══ ولمَ لا تُشتقّ من وسائل السداد الحقيقيّة ═══
     *
     * السدادُ الفعليّ يقبل `cash` أو `bank` وحدهما — انظر
     * `SupplierInvoiceController::pay`. وهما وجهةُ المال في الدفتر، لا ما
     * يقوله التاجر لمورّده. و«بطاقة» تُسدَّد من البنك في النهاية، لكنّ من
     * يكتب الأمر يكتب ما اتّفق عليه لا ما سيقوله الدفتر بعد شهر.
     *
     * فهما قائمتان لأنّهما شيئان: هذه خطّةٌ تُكتب على الورقة، وتلك وجهةُ
     * مالٍ تُكتب في القيد. وخلطُهما يجعل «آجل» تبحث عن حسابٍ يخرج منه المال.
     *
     * @var list<string>
     */
    public const METHODS = ['نقدي', 'تحويل بنكي', 'بطاقة', 'آجل'];

    /**
     * «آجل» — لا سدادَ مع التسليم.
     *
     * وهي في القائمة لأنّ من يكتب الأمر يختار بين «سأدفع عند الاستلام» و
     * «سأدفع بعد مدّة» في الموضع نفسه — لا في شاشتين.
     */
    public const CREDIT = 'آجل';

    /**
     * وسيلةُ السداد كما تُقرأ على الورقة — مترجَمةً.
     *
     * ═══ ولمَ تُترجَم قيمةٌ لا عنوان ═══
     *
     * «تحويل بنكي» ليست نصًّا كتبه التاجر — هي قيمةٌ من قائمةٍ مغلقة يكتبها
     * النظام. وورقةٌ إنجليزيّةٌ تقول «Payment method: تحويل بنكي» تُقرأ
     * ورقةً نصفُها بلغةٍ ونصفُها بأخرى. أمّا اسمُ الصنف وملاحظةُ المورّد
     * فنصٌّ كتبه صاحبُه — يبقى كما كتبه.
     *
     * والمفتاحُ الغائبُ يُعرض باسمه: وسيلةٌ تُضاف تظهر ولو لم تُترجَم بعد،
     * لا تختفي لأنّ أحدًا نسي سطرًا.
     */
    public static function methodLabel(?string $method): string
    {
        return $method === null || $method === '' ? '' : __($method);
    }

    /** مددُ السداد المعروضة — ومصدرُها واحد تقرأ منه الشاشةُ والمصادقة */
    public const TERMS = [0, 7, 15, 30, 45, 60, 90];

    /** المورّدُ الذي تُفتح عليه شاشةُ أمر الشراء — مفتاحُ إعدادٍ للمتجر */
    public const DEFAULT_SUPPLIER = 'default_supplier_id';

    /**
     * المورّدُ الافتراضيّ — ويُتحقّق من صفّه عند كلّ قراءة.
     *
     * مورّدٌ حُذف يترك في الإعدادات رقمًا لا صفَّ له. وشاشةٌ تفتح عليه تعرض
     * حقلًا مختارًا بلا اسم، ويُردّ الحفظُ بـ«المورّد المحدد غير صالح» عن
     * اختيارٍ لم يختره أحد.
     *
     * ═══ ومورّدٌ واحد يُختار وحدَه ═══
     *
     * محلٌّ له مورّدٌ واحد لا معنى لأن يُسأل عنه في كلّ أمر — والقائمةُ ذاتُ
     * الخيار الواحد ليست خيارًا. والمضبوطُ صراحةً يسبقه: من ضبط مورّدًا ثمّ
     * أضاف ثانيًا يبقى على ما ضبط.
     */
    public static function defaultSupplierId(int $businessId): ?int
    {
        $id = Setting::where('business_id', $businessId)
            ->where('key', self::DEFAULT_SUPPLIER)->value('value');

        if (filled($id) && Supplier::where('business_id', $businessId)->whereKey($id)->exists()) {
            return (int) $id;
        }

        $only = Supplier::where('business_id', $businessId)->limit(2)->pluck('id');

        return $only->count() === 1 ? (int) $only->first() : null;
    }

    /**
     * رقمُ الأمر التالي — تسلسلٌ تحت قفلٍ على صفّ المتجر.
     *
     * وكان `'PO-'.random_int(10000, 99999)`: تسعون ألف احتمال، ولا فهرسَ
     * تفرّدٍ على العمود. فمتجرٌ يكتب مئتي أمرٍ احتمالُ تصادمِ رقمين فيه يقارب
     * العشرين بالمئة (مفارقةُ أعياد الميلاد) — ورقمان لأمرين يجعلان البحث
     * يفتح غيرَ ما طُلب، والمطابقةَ تُنسب إلى الأمر الخطأ.
     *
     * والقفلُ ضروريّ: نافذتان تفتحان الشاشة معًا تقرآن آخرَ رقمٍ فتكتبانه
     * كلتاهما.
     */
    public static function nextNumber(int $businessId): string
    {
        return DB::transaction(function () use ($businessId) {
            Business::whereKey($businessId)->lockForUpdate()->first();

            $last = PurchaseOrder::where('business_id', $businessId)
                ->where('number', 'like', 'PO-%')
                ->orderByDesc('id')->value('number');

            /*
             * والأرقامُ القديمة عشوائيّة (`PO-48213`)، فآخرُها ليس أكبرَها.
             *
             * فيُقرأ الأكبرُ عددًا لا الأحدثُ صفًّا حين يُخلط القديمُ بالجديد،
             * وإلّا لَعاد التسلسلُ إلى رقمٍ استُعمل.
             */
            $highest = (int) PurchaseOrder::where('business_id', $businessId)
                ->where('number', 'like', 'PO-%')
                ->get(['number'])
                ->map(fn ($r) => (int) substr($r->number, 3))
                ->max();

            $n = max($highest, $last ? (int) substr($last, 3) : 0) + 1;

            return 'PO-'.str_pad((string) $n, 6, '0', STR_PAD_LEFT);
        });
    }
}
