<?php

namespace App\Support;

/**
 * صرفُ النقاط إلى مال — رقمٌ واحد يقرؤه الطرفان.
 *
 * كان مكتوبًا في ثلاثة مواضع: ثابتٌ خاصّ في نقطة البيع، ومثلُه في
 * `usePosCart.ts`، وتعليقٌ في شاشة برنامج الولاء يقول «١٠٠ نقطة = وحدة
 * عملة». وشاشةُ الإعدادات — وهي التي تحدّ نسبة الاكتساب — لم تكن تعرفه
 * أصلًا، فحدّت النسبة بألف: أي عشرةَ أضعاف ما يجعل البرنامج يردّ للزبون
 * فاتورته كاملة.
 */
class Loyalty
{
    /**
     * كم نقطةً تساوي وحدةَ عملةٍ واحدة عند الاستبدال.
     *
     * ويجب أن تطابق POINTS_PER_UNIT في `resources/js/hooks/usePosCart.ts`:
     * الشاشة تحسب الخصم لتعرضه، والخادم يحسبه ليكتبه — ولو افترقا لقرأ
     * الزبون رقمًا ودفع آخر.
     */
    public const POINTS_PER_UNIT = 100;

    /**
     * أقصى نسبة اكتسابٍ يجوز أن تُحفظ.
     *
     * نسبةُ الاكتساب نقاطٌ لكلّ وحدة شراء، والاستبدال يحوّلها إلى مالٍ
     * بالمقسوم أعلاه. فمنحُ مئة نقطةٍ لكلّ ريال يعني ريالًا كاملًا يعود إلى
     * الزبون عن كلّ ريالٍ يدفعه — والزيادة عليها تعني أن يخرج من الصندوق
     * أكثر ممّا دخله. وليس هذا سخاءً مبالغًا فيه يُترك للتاجر: هو حلقةٌ
     * لا تُغلق، يشتري بها الزبون بنقاطٍ يكسب منها نقاطًا.
     */
    public static function maxEarnRate(): float
    {
        // ما دون المقسوم بخطوةٍ واحدة: أقصى ما يبقى تحت مئة بالمئة
        return self::POINTS_PER_UNIT - 0.1;
    }

    /** كم بالمئة من فاتورته تعود إلى الزبون عند هذه النسبة */
    public static function cashbackPercent(float $rate): float
    {
        return round($rate / self::POINTS_PER_UNIT * 100, 1);
    }
}
