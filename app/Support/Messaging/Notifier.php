<?php

namespace App\Support\Messaging;

/**
 * قناةُ إيصالٍ — تقول عن نفسها هل تُوصِل، وتُرسل.
 *
 * ═══ الحدُّ الذي يُصمَّم الآن ويُنفَّذ بريدًا ═══
 *
 * النظامُ الأساسيّ يعرف «أرسل هذا إلى هذا الشخص» ولا يعرف WABA ولا
 * قوالبَ معتمَدة ولا نافذةَ ٢٤ ساعة — تلك شأنُ القناة وحدها (§21). فيُكتب
 * الحدُّ اليوم، ويُنفَّذ بالبريد لأنّه ما يُوصِل شيئًا حقيقيًّا الآن،
 * ويُثبت الشكلَ قبل أن يُدفع ثمنُ واتساب.
 *
 * ═══ و`configured()` ترث درسَ `Mailer` ═══
 *
 * «`log` و`array` مُرسلان صالحان في نظر لارافيل… فالشاشةُ تقول أرسلنا
 * والرسالةُ في ملفّ سجلّ». فالقناةُ تقول عن نفسها هل تُوصِل، والشاشةُ
 * تُخفي بابًا لا يفتح، والمسارُ يرفض حتى لمن عرف الرابط.
 */
interface Notifier
{
    /** `email` · `whatsapp` · `sms` */
    public function channel(): string;

    /** أتُوصِل هذه القناةُ شيئًا إلى أحدٍ فعلًا؟ */
    public function configured(): bool;

    /** من يُوصِل فعلًا — `postmark` · `smtp` · `meta` — كما يُكتب في السجلّ ويُقرأ في الـwebhook */
    public function provider(): string;

    public function send(MessageIntent $intent): MessageResult;
}
