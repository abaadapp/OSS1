<?php

namespace App\Support;

use App\Models\Order;

/**
 * إلى من تذهب الرسالة — إلى المشتري، لا إلى المستلِم.
 *
 * وهذا قرارُ عملٍ لا تفصيلَ تقنيّ: نصف طلبات محلّ الورد مفاجأة. رسالةٌ تقول
 * «طلبك جاهز» تصل إلى من يُفترض ألّا يعرف أنّ هناك طلبًا تُفسد الهديّة —
 * ولا يُصلحها اعتذار.
 *
 * فالمستلِم لا يُرسَل إليه في هذه النسخة إطلاقًا. ومن أراد إشعارَه فذلك
 * قرارٌ يُتّخذ صراحةً بمقبضٍ يراه التاجر ويفهم أثره، لا افتراضٌ يُبنى في
 * الكود ويُكتشف بعد أوّل مفاجأةٍ أُفسدت.
 */
class WhatsAppRecipient
{
    /**
     * رقم المشتري بصيغة واتساب، أو لا شيء.
     *
     * ومصدره العميل المربوط بالطلب وحده — لا عمود هاتفٍ على الطلب أصلًا.
     * وبيعةُ المارّ لا عميلَ لها ولا رقم، فتُقيَّد ممتنعةً بسببها ولا تُعامَل
     * خطأً: أكثر بيعات المحلّ كذلك، ولو عُدّت أخطاءً لَامتلأ السجلّ بما لا
     * يُصلَح.
     */
    public static function forOrder(Order $order): ?string
    {
        return WhatsAppPhone::normalize($order->customer?->phone);
    }
}
