<?php

namespace App\Support\Website\Domain;

use App\Models\WebsiteDomain;

/**
 * من يتولّى نطاقَ التاجر — وهو ليس افنت بلسَ بالضرورة.
 *
 * ربطُ نطاقٍ يملكه التاجر عملٌ من ثلاثة أجزاء: أن يُوجَّه سجلُّ DNS إلينا،
 * وأن نتحقّق أنّه وُجّه، وأن تُصدَر له شهادةٌ ويُجدَّد إصدارُها. والجزء
 * الثالث وحده يجعل بناءَه بأنفسنا قرارًا كبيرًا: شهادةٌ لكلّ نطاقٍ لكلّ
 * تاجر، تُصدَر وتُجدَّد وتُراقَب.
 *
 * ولهذا يُوصَف العملُ هنا ولا يُنفَّذ: اليوم مزوّدُنا يدويّ — نقول للتاجر
 * أيَّ سجلٍّ يضيف ثمّ نسأل DNS. وغدًا قد يكون مزوّدًا يتولّى الثلاثة معًا.
 * وربطُ نموذجِ النطاق بأحدهما مباشرةً يجعل تبديلَه هجرةً في الجدول ونصًّا
 * في الشاشة — لا سطرًا في مزوّد الخدمات.
 *
 * والواجهةُ تقول أقلَّ ما يلزم: ماذا يفعل التاجر، وهل صحّ، ولا شيءَ عن
 * كيفَ يعرف المزوّدُ ذلك.
 */
interface CustomDomainProvider
{
    /** اسمُ المزوّد كما يُحفظ في الصفّ */
    public function name(): string;

    /**
     * ما يجب أن يضيفه التاجر في سجلّاته — أو قائمةٌ فارغة إن كان المزوّد
     * يتولّى التوجيه بنفسه.
     *
     * @return list<array{type: string, name: string, value: string}>
     */
    public function instructions(WebsiteDomain $domain): array;

    /**
     * سجِّل العنوان عند المزوّد — ويردّ معرّفَه عنده إن كان له معرّف.
     *
     * ولا يرمي عند الفشل: يردّ `null` ويُقال السببُ في `check`. فشلُ
     * تسجيلٍ عند مزوّدٍ خارجيّ ليس خطأً في افنت بلس، ولا يُرى للتاجر صفحةَ
     * خطأ لأنّ خدمةً ثالثة تأخّرت.
     */
    public function register(WebsiteDomain $domain): ?string;

    /** أيشير هذا العنوان إلينا الآن؟ */
    public function check(WebsiteDomain $domain): DomainCheck;

    /** يُرفع من عند المزوّد حين يفكّه التاجر */
    public function forget(WebsiteDomain $domain): void;
}
