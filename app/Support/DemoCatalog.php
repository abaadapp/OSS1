    /**
     * يبني الكتالوج في الشركة التجريبيّة.
     *
     * @return array<string, Product> البنودُ بالرمز — يقرؤها من يبني العروضَ بأسعارها
     */
    public static function build(Business $business): array
    {
        DemoGuard::assertDemo($business);
        $bid = (int) $business->id;

        $categories = [];
        foreach (self::SECTIONS as $code => [$name, $en, $icon, $color]) {
            $categories[$code] = Category::create([
                'business_id' => $bid, 'name' => $code.' '.$name, 'name_en' => $en, 'icon' => $icon, 'color' => $color,
            ]);
        }

        $out = [];
        foreach (self::ITEMS as $code => [$name, $en, $description, $unit, $price, $note, $kind, $cost]) {
            $out[$code] = Product::create([
                'business_id' => $bid,
                'category_id' => $categories[substr($code, 0, 2)]->id,
                'name' => $name, 'name_en' => $en,
                'description' => self::describe($description, $unit, $price, $note),
                'sku' => 'EP-'.$code,
                'kind' => $kind,
                'price' => $price, 'cost' => $cost,
                'quantity' => $kind === Product::ITEM ? 4000 : 0,
                'alert_qty' => $kind === Product::ITEM ? 500 : 0,
                'tax' => 5, 'discount' => 0, 'active' => true,
            ]);
        }

        foreach (self::PACKAGES as $code => [$name, $en, $description, $first, $extra, $contents]) {
            $package = $out[$code] = Product::create([
                'business_id' => $bid, 'category_id' => $categories['07']->id,
                'name' => $name, 'name_en' => $en,
                'description' => self::describe($description, 'اليوم الأول', $first, $first > 0 ? null : 'حسب نطاق العمل')
                    .($extra ? ' — اليوم الإضافي: '.$extra.' ر.ع.' : '').' يمكن إضافة منتجات وخدمات من الكتالوج.',
                'sku' => 'EP-'.$code, 'kind' => Product::PACKAGE,
                'price' => $first, 'cost' => 0, 'quantity' => 0, 'alert_qty' => 0, 'tax' => 5, 'discount' => 0, 'active' => true,
            ]);

            $sort = 0;
            foreach ($contents as $item => $qty) {
                PackageItem::create([
                    'business_id' => $bid, 'package_id' => $package->id, 'item_id' => $out[$item]->id,
                    'quantity' => $qty, 'unit' => self::ITEMS[$item][3], 'sort_order' => $sort++,
                ]);
            }

            if ($extra) {
                $out[$code.'x'] = Product::create([
                    'business_id' => $bid, 'category_id' => $categories['07']->id,
                    'name' => $name.' — يوم إضافي', 'name_en' => $en.' — Additional day',
                    'description' => 'كل يوم إضافي بعد اليوم الأول من '.$name.'، بالمشمولات نفسها.',
                    'sku' => 'EP-'.$code.'X', 'kind' => Product::SERVICE,
                    'price' => $extra, 'cost' => 0, 'quantity' => 0, 'alert_qty' => 0, 'tax' => 5, 'discount' => 0, 'active' => true,
                ]);
            }
        }

        return $out;
    }

    /** وحدةُ التسعير في البند — `unit` في سطر العرض */
    public static function unit(string $code): ?string
    {
        return self::ITEMS[$code][3] ?? (isset(self::PACKAGES[rtrim($code, 'x')]) ? (str_ends_with($code, 'x') ? 'يوم إضافي' : 'اليوم الأول') : null);
    }

    private static function describe(string $description, string $unit, float $price, ?string $note): string
    {
        $pricing = match (true) {
            $price <= 0 => $note ?? 'حسب نطاق العمل',
            $note === 'يبدأ من' => 'يبدأ من '.self::money($price).' ر.ع '.$unit,
            default => self::money($price).' ر.ع '.$unit.($note ? ' ('.$note.')' : ''),
        };

        return $description.' — السعر: '.$pricing.'.';
    }

    private static function money(float $v): string
    {
        return rtrim(rtrim(number_format($v, 3, '.', ','), '0'), '.');
    }
