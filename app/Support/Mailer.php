<?php

namespace App\Support;

use App\Models\Business;

/**
 * هل يستطيع النظام إرسال بريدٍ فعلًا؟
 *
 * `log` و`array` مُرسلان صالحان في نظر لارافيل: لا يرميان خطأً، ويعودان
 * بنجاح. فـMail::send تنجح، والشاشة تقول «أرسلنا الرابط»، والرسالة في ملفّ
 * سجلٍّ على الخادم أو في الذاكرة. نجاحٌ كاذب لا يكشفه إلا من يفتح بريده
 * وينتظر.
 *
 * فيُسأل هنا مرّةً واحدة: الشاشة تُخفي الباب الذي لا يفتح، والمسار يرفض
 * الطلب حتى لمن يعرف الرابط، وpreflight يمنع الإطلاق. ثلاثة مواضع تقرأ
 * حقيقةً واحدة، فلا يتخلّف موضعٌ يوم يُضبط SMTP.
 *
 * ═══ ورابعٌ: مفاتيحُ الإشعارات ═══
 *
 * وفي «الإعدادات ‹ الإشعارات» ثلاثةُ مفاتيح تَعِد صراحةً: «يُرسل إلى بريد
 * صاحب النشاط عند إتمام أي عملية بيع»، و«يصل آخر اليوم بمبيعات اليوم». وهي
 * تُحفظ وتُقرأ في نقطة البيع وفي أمرَي الجدولة — ثمّ تمرّ كلُّها بـ
 * `Mail::send` التي تنجح على مُرسِلٍ ساقط. فيفتحها التاجر ويطمئنّ، ولا يصله
 * شيءٌ أبدًا، ولا يعرف لماذا. فتُقال الحقيقةُ فوق المفاتيح — ولا تُطفأ:
 * الإعدادُ اختيارُ صاحبه، ويجده كما تركه يوم يُضبط البريد.
 */
class Mailer
{
    /** مُرسِلات لا تُوصل شيئًا إلى أحد */
    private const SINKS = ['log', 'array', 'null'];

    public static function configured(): bool
    {
        $driver = (string) config('mail.default');

        if (in_array($driver, self::SINKS, true)) {
            return false;
        }

        /*
         * وsmtp بلا مضيف ليس أفضل حالًا: يُرمى الاتصال على «» فيفشل الإرسال
         * وقت التنفيذ لا وقت الإعداد — أي عند المستخدم لا عند من ضبط الخادم.
         */
        if ($driver === 'smtp' && blank(config('mail.mailers.smtp.host'))) {
            return false;
        }

        /*
         * ومزوّدُ HTTP بلا مفتاح مثله: لارافيل تقبل الإعداد وتبني المُرسِل،
         * ثم يُرفض الطلب عند المزوّد وقت الإرسال. فيُسأل عن المفتاح هنا لا
         * هناك — والشاشة تقول الحقيقة قبل أن يعتمد عليها أحد.
         */
        $keys = ['resend' => 'services.resend.key', 'postmark' => 'services.postmark.key'];
        if (isset($keys[$driver]) && blank(config($keys[$driver]))) {
            return false;
        }

        return true;
    }

    /**
     * وهل يصل إلى **هذا** المتجر؟ — مُرسِلٌ حيّ وبريدٌ يُرسَل إليه.
     *
     * `Mail::to(null)` لا مُرسَلَ إليها: متجرٌ لم يكتب بريده في «بيانات
     * النشاط» لا يبلغه شيءٌ مهما كان الخادم مضبوطًا.
     */
    public static function deliverable(?Business $business): bool
    {
        return self::configured() && filled(trim((string) ($business?->email ?? '')));
    }

    /**
     * سببُ التعذّر نصًّا — أو `null` إن كان البريد يصل.
     *
     * ولكلٍّ سببُه: من ينقصه بريدٌ يُصلحه بنفسه من الشاشة نفسها، ومن ينقصه
     * ضبطُ الخادم لا يملك إصلاحه — فلا يُرسَل إلى حقلٍ يملؤه بلا فائدة.
     */
    public static function reason(?Business $business): ?string
    {
        if (! self::configured()) {
            return __('إرسالُ البريد غير مضبوط على الخادم — تُحفظ هذه الخيارات ولا يصل منها شيء حتى يُضبط.');
        }

        if (blank(trim((string) ($business?->email ?? '')))) {
            return __('لا بريد إلكتروني لنشاطك — اكتبه في «بيانات النشاط» ليصلك ما تفتحه هنا.');
        }

        return null;
    }
}
