<?php

namespace App\Support;

use App\Models\Order;
use Illuminate\Support\Facades\DB;

/**
 * نقلُ حالة الطلب — بابٌ واحد تدخل منه شاشة المبيعات ولوحة التجهيز.
 *
 * كان الفحص والنقل مكتوبين مرّتين، حرفًا بحرف، في `OrderDetailController`
 * و`PreparationController`. والتعليق فوقهما يحذّر من حارسين يفترقان — ثمّ
 * يكتب الحارس مرّتين. فأوّلُ تعديلٍ يقع في أحدهما يجعل العامل يستطيع من
 * لوحته ما لا يستطيعه صاحبُ المحلّ من شاشته، أو العكس.
 *
 * وفيه أمران لم يكونا في أيّ من النسختين:
 *
 * أوّلًا القفل. الحال تُقرأ ثمّ يُكتب فوقها، وبين القراءة والكتابة فرجة.
 * فموظّفان على اللوحة نفسها — وهي معروضةٌ على كلّ شاشات المحلّ — يقرآن
 * «قيد التجهيز» معًا: أحدهما ينقل إلى «جاهز» والآخر يُلغي. فيردّ الإلغاء
 * البضاعة ويمحو قيد الدخل، ثمّ تكتب الكتابة الأخرى «جاهز» فوقه: طلبٌ حيٌّ
 * على اللوحة، بضاعتُه عادت إلى الرفّ ولا قيدَ دخلٍ له. ولا شاشة تقول ذلك.
 *
 * وثانيًا أنّ الرفض يُرى. كان يُردّ بـ`withErrors`، واللوحة لا تعرض إلّا
 * `flash.toast`. فمن ضغط «جاهز» على طلبٍ أُلغي قبل لحظة لا يرى شيئًا
 * إطلاقًا: لا رسالة ولا تغيّر. فيضغط ثانيةً، ثمّ ثالثة، ثمّ يسأل صاحب
 * المحلّ عن لوحةٍ «لا تعمل».
 */
final class OrderTransition
{
    /**
     * ينقل الطلب إن جاز — ويردّ رسالة الرفض إن لم يجز.
     *
     * @return string|null  null تعني أنّ النقل تمّ
     */
    public static function apply(Order $order, string $to): ?string
    {
        return DB::transaction(function () use ($order, $to) {
            // الحال تُقرأ تحت قفل: ما قرأه المتصفّح قد تجاوزه غيرُه
            $fresh = Order::whereKey($order->id)->lockForUpdate()->first();

            if (! $fresh) {
                return __('لم يعد هذا الطلب موجودًا.');
            }

            if (! OrderStatus::canMove($fresh->status, $to)) {
                return __('لا يمكن نقل الطلب من «:from» إلى «:to».', [
                    'from' => $fresh->status, 'to' => $to,
                ]);
            }

            /*
             * الإلغاء يردّ ما أخذه البيع — ولا يكفي أن تُكتب الكلمة في عمود.
             *
             * انظر `OrderCorrection::cancel`: المخزون والنقاط والكوبون وقيد
             * الدخل. وكان الأربعة تبقى، والتقارير تستثني الملغى فيبدو الأمر
             * سليمًا في الشاشة والخلل تحتها.
             */
            if ($to === OrderStatus::CANCELLED) {
                /*
                 * والرفضُ يُقال للمنادي لا يُرمى في وجهه.
                 *
                 * هذه الدالّة تردّ رسالةً تُعرض في الشاشة، فاستثناءٌ يخرج
                 * منها يصير خمسمئةً على موظّفٍ ضغط زرًّا مشروعًا.
                 */
                try {
                    OrderCorrection::cancel($fresh);
                } catch (\RuntimeException $e) {
                    return $e->getMessage();
                }
            } else {
                $fresh->update(['status' => $to]);
            }

            // ونسخةُ المنادي تُساير ما وقع، فلا يُقيَّد في السجلّ حالٌ قديمة
            $order->setAttribute('status', $to);
            $order->syncOriginalAttribute('status');

            return null;
        });
    }
}
