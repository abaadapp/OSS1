<?php

namespace App\Support;

/**
 * الأرقام تُكتب إنجليزيّة مهما كانت لغة لوحة المفاتيح.
 *
 * لوحةُ المفاتيح العربية على الهاتف تكتب «٥٠٠» لا «500»، والتاجر لا يبدّل
 * لغتها لأجل حقل سعر. وكان ما يُكتب بها **يُرفض**: `is_numeric('٥٠٠')` كاذبة
 * في PHP، فتردّ طبقةُ التحقّق «يجب أن يكون رقمًا» على رقمٍ مكتوبٍ صحيحًا —
 * رسالةٌ لا يفهمها من كتبه، لأنّه يراه رقمًا وهو كذلك.
 *
 * وكان النظام يُصلح هذا لعشرين اسمَ حقلٍ ماليّ مكتوبةً باليد (`price`
 * و`amount` وأخواتها) — فالكميّة والهاتف ونسبة الضريبة ورقم التسجيل وسقف
 * التنبيه كلُّها خارج القائمة. وقائمةٌ تُكتب باليد تنسى التاليَ دائمًا.
 * فصار التحويل **على كلّ ما يصل**، وقاعدتُه واحدة: الرقم رقمٌ أيًّا كان
 * اسم حقله.
 *
 * ولا يُمسّ إلّا الرقم: الحروف تبقى كما كُتبت، فـ«شارع ٢٣» تصير «شارع 23»
 * ولا يتبدّل حرفٌ فيها.
 */
class Numerals
{
    /**
     * الأرقام الهندية (العربية) والفارسية → اللاتينية.
     *
     * والفاصلتان معهما: `٫` عشريّةٌ و`٬` للآلاف، ولا تردان في نصٍّ عربيّ
     * إلّا مع رقم. أمّا الفاصلة العربية `،` فتردُ في الكلام كثيرًا، فلا
     * تُمسّ — وإلّا لتبدّل ترقيمُ كلّ ملاحظةٍ يكتبها التاجر.
     */
    private const MAP = [
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        '٫' => '.', '٬' => ',',
    ];

    /** الأرقام إنجليزيّة، وما عداها كما هو */
    public static function toAscii(string $value): string
    {
        return strtr($value, self::MAP);
    }

    /** هل في النصّ رقمٌ غيرُ لاتينيّ؟ */
    public static function has(string $value): bool
    {
        return $value !== self::toAscii($value);
    }
}
