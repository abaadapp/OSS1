<?php

namespace App\Support;

use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;

/**
 * كتابةٌ يُتوقَّع أن تصطدم — وتُكتب بحيث لا تُسقط ما حولها.
 *
 * ═══ ما كان يقع ═══
 *
 * أربعةُ مواضع في النظام تكتب صفًّا وتتوقّع أن يردّها فهرسٌ فريد أحيانًا،
 * فتلتقط الاصطدام وتمضي: رسالةُ واتساب مكرّرة، ورصيدُ فرعٍ يُنشأ مرّتين،
 * ورمزُ مستندٍ يطلبه صندوقان معًا، ورقمُ فاتورةٍ يسبق إليه كاشيرٌ آخر.
 *
 * وهذا صحيحٌ على SQLite وMySQL: الاستعلامُ يفشل وحدَه، والمعاملةُ تمضي.
 *
 * **وهو ممنوعٌ على PostgreSQL.** أوّلُ أمرٍ يفشل داخل معاملة يُجهضها كلَّها،
 * فكلُّ أمرٍ بعده يُردّ بـ`25P02` حتى تُلغى. فالتقاطُ الاستثناء لا يُنقذ
 * شيئًا: المعاملةُ ميّتةٌ في يدك، وما بعدها يسقط.
 *
 * وقاعدةُ الإنتاج PostgreSQL. فتغييرُ حالةِ طلبٍ يبعث رسالةً مكرّرة كان
 * **يُجهض تغييرَ الحالة نفسِه** — لا الرسالةَ وحدها. وحلقةُ إعادة المحاولة
 * على رقم الفاتورة في نقطة البيع كانت بلا معنى: المحاولةُ الثانية تقع في
 * معاملةٍ مجهَضة.
 *
 * ═══ والعلاج نقطةُ حفظ ═══
 *
 * `DB::transaction` داخل معاملةٍ قائمة تكتب `SAVEPOINT`، وتعود إليه عند
 * الاستثناء (`ROLLBACK TO SAVEPOINT`) — فتموت الكتابةُ وحدَها وتبقى
 * المعاملةُ حيّة. وخارج أيّ معاملةٍ هي معاملةٌ عاديّةٌ لا ضرر فيها.
 *
 * وموضعٌ واحد يقرؤه الأربعة: قاعدةٌ تُكتب أربع مرّاتٍ تُنسى في الخامسة.
 */
final class Contention
{
    /**
     * كتابةٌ تُردّ بـnull إن اصطدمت بفهرسٍ فريد.
     *
     * والقيمةُ الراجعة قيمةُ الكتابة نفسِها — فلا تُستعمل مع كتابةٍ تردّ
     * `null` في حال النجاح، إذ لا يُفرَّق حينها بين الاصطدام والنجاح.
     */
    public static function attempt(callable $write): mixed
    {
        try {
            return DB::transaction($write, 1);
        } catch (UniqueConstraintViolationException) {
            return null;
        }
    }

    /**
     * كتابةٌ تُعاد عند الاصطدام — كلُّ محاولةٍ في نقطة حفظها.
     *
     * وبلا ذلك كانت المحاولةُ الثانية تقع في معاملةٍ أجهضتها الأولى، فتفشل
     * الخمسُ محاولاتٍ لسببٍ واحد وقع مرّةً — ويُردّ الكاشيرُ عن بيعةٍ رقمُها
     * كان متاحًا.
     *
     * @throws UniqueConstraintViolationException بعد آخر محاولة
     */
    public static function retry(callable $write, int $times = 5): mixed
    {
        for ($attempt = 1; $attempt <= $times; $attempt++) {
            try {
                return DB::transaction($write, 1);
            } catch (UniqueConstraintViolationException $e) {
                if ($attempt === $times) {
                    throw $e;
                }
            }
        }

        // لا يُبلَغ: الحلقةُ تعود أو ترمي
        throw new \LogicException('unreachable');
    }
}
