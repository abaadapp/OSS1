<?php

namespace App\Support;

/**
 * المالُ مكتوبًا — قاعدةٌ واحدة يقرؤها كلُّ ما يعرض مبلغًا.
 *
 * ═══ العطبُ الذي وُلد منه هذا الملفّ ═══
 *
 * كان قرارُ «كيف يُكتب المبلغ» مكتوبًا في خمسة مواضع على الأقلّ في مسار
 * المستند وحده: `DocumentPaper::money`، ومُغلَقٌ في قالب فاتورة العميل،
 * ومثلُه في القالب الحراريّ، وسطورٌ في صفحة الرابط العامّ، وسطرٌ في
 * متحكّمها. وأربعةٌ منها تكتب `number_format($v, 3)` و`ر.ع` **مثبَّتَين
 * في الشفرة**.
 *
 * والنظامُ يعرف عملةَ التاجر ويحفظها: صفٌّ في `currencies` ومنازلُ عشرية
 * في الإعدادات وموضعٌ للرمز — تقرؤها `Demo::currencyFor` وتكتب بها اللوحةُ
 * كلُّها. فوقع أنّ تاجرًا في دبي عملتُه الدرهم:
 *
 *   • لوحتُه تكتب  →  ‏5.25 د.إ
 *   • وفاتورتُه تكتب →  ‏5.250 ر.ع
 *
 * رقمٌ بمنزلةٍ زائدة، وعملةُ بلدٍ آخر، على الورقة التي يرسلها باسمه. وهو
 * لا يظهر في اختبارٍ يُكتب بالريال العمانيّ — إذ يوافق المثبَّتُ الصوابَ
 * مصادفةً — ولا في مراجعةٍ بالعين لأنّ الرقم «يبدو صحيحًا».
 *
 * ═══ ولمَ صنفٌ مستقلّ لا تابعٌ في `Demo` ═══
 *
 * `Demo` تقرأ الجلسةَ ومتجرَ الداخل. والورقةُ تُرسم حيث لا جلسة: رابطٌ
 * عامٌّ يفتحه زبونٌ لا حساب له، وطابورٌ يعالج متجرين بالتتابع. فالكتابةُ
 * تُفصل عن «مَن يقرأ» لتصير تابعًا خالصًا: مبلغٌ ووصفُ عملة، فنصّ.
 *
 * والوصفُ يصل كاملًا لا رمزًا: المنازلُ العشرية اختيارُ التاجر (من صفرٍ
 * إلى أربع)، وموضعُ الرمز اختيارُه أيضًا. ورمزٌ وحده يُسقط الاثنين.
 */
final class Money
{
    /**
     * منازلُ عملةٍ لا تُعلن منازلَها.
     *
     * الريالُ العمانيّ والدينارُ الكويتيّ والبحرينيّ ثلاثُ منازل — بيسةٌ
     * وفلسٌ من ألف، لا من مئة. وسقوطُها إلى منزلتين يمحو خانةً من كلّ مبلغ.
     */
    private const THREE = ['OMR', 'KWD', 'BHD'];

    /**
     * دقّةُ التخزين — ثلاثُ منازل في كلّ عمودٍ ماليٍّ في القاعدة.
     *
     * ثمانيةٌ وتسعون عمودًا `decimal(…, 3)`، وثلاثُمئةٍ وتسعةُ مواضعَ تحسب
     * بـ`round(…, 3)`، وعتبةُ التسوية `0.0005` — نصفُ المنزلة الثالثة —
     * مكتوبةٌ في عشرة ملفّات: `Ledger::trialBalance` و`JournalEntry::isBalanced`
     * و`SupplierInvoices::TOLERANCE` و`CustomerInvoice::outstandingSql` وغيرها.
     *
     * فهي عقدٌ في النظام لا رقمٌ في دالّة. وما دون المنزلة الثالثة لا يُخزَّن
     * أصلًا، فلا معنى لعرضه.
     */
    private const SCALE = 3;

    /** وصفُ عملةِ متجرٍ بعينه — لا عملةُ من يقرأ */
    public static function of(int $businessId): array
    {
        return Demo::currencyFor($businessId);
    }

    /**
     * المبلغُ مكتوبًا بعملته — رقمًا ورمزًا وموضعَ رمزٍ كما اختار التاجر.
     *
     * @param  array<string, mixed>  $currency  وصفٌ من `of()` أو `Demo::baseCurrency()`
     */
    public static function format(float $value, array $currency): string
    {
        // الترجمةُ هنا لا عند تعريف العملة، لتشمل الرمزَ القادمَ من القاعدة أيضًا
        $symbol = __((string) ($currency['symbol'] ?? ''));
        $amount = self::amount($value, $currency);

        return ($currency['before'] ?? false) ? $symbol.' '.$amount : $amount.' '.$symbol;
    }

    /**
     * الرقمُ وحده بلا رمز — لجدولٍ يحمل رأسُه العملةَ مرّةً واحدة.
     *
     * @param  array<string, mixed>  $currency
     */
    public static function amount(float $value, array $currency): string
    {
        return number_format($value, self::shown($value, $currency), '.', ',');
    }

    /**
     * كم منزلةً تُكتب لهذا المبلغ بعينه — منازلُ العملة ما لم تُخفِ رقمًا.
     *
     * ═══ ما لا يُخزَّن لا يُعرض، وما يُخزَّن لا يُخفى ═══
     *
     * الحسابُ يُقرَّب إلى ثلاثِ منازل دائمًا، والعرضُ إلى منازل العملة.
     * وبينهما فجوةٌ لعملةٍ منزلتاها اثنتان:
     *
     *   بندٌ بـ‏12.28 درهمًا وضريبةُ 5٪  →  0.614  →  إجماليٌّ **12.894**
     *   والورقةُ كانت تكتب                →  «‏12.89 د.إ»
     *
     * فيدفع الزبونُ ما قرأ — 12.89 — ويبقى على الفاتورة **0.004**. فتقول
     * الشاشةُ «مدفوعة جزئيًا» عن ورقةٍ سُدّدت بالكامل بحسب ما كُتب عليها،
     * وتقول في العمود نفسِه إنّ الباقيَ «‏0.00 د.إ». ورقةٌ تناقض نفسها: تعرض
     * رقمًا وتطالب بغيره، وتبقى في تقرير الأعمار إلى الأبد.
     *
     * فالقاعدةُ: **لا تُحذف منزلةٌ فيها رقم**. تبدأ من اختيار التاجر وتزيد
     * منزلةً منزلةً حتى يصير المكتوبُ هو المخزَّن. فـ«‏5.25 د.إ» تبقى كما هي —
     * الصفرُ الثالث لا يحمل خبرًا — و«‏12.894 د.إ» تُكتب بثلاث لأنّ الثانية
     * تكذب.
     *
     * والعتبةُ `0.0005` هي عتبةُ التسوية نفسُها في النظام: أصغرُ فرقٍ يمكن أن
     * يقع بين مخزَّنَين بثلاث منازل هو `0.001`، فما دونه ضجيجُ فاصلةٍ عائمة
     * لا خبر.
     *
     * ولمَ لا يُقرَّب **الحساب** إلى منازل العملة بدلًا من ذلك: لأنّ التقريب
     * يقع في ثمانيةِ مواضعَ تصنع مالًا من نسبة — ضريبةُ البيع، وضريبةُ فاتورة
     * العميل، وضريبةُ الشراء (ونسختُها في `lib/purchase-totals.ts` يقابلها
     * اختبار)، والقسائم، والعمولات، والإهلاك، وخصمُ المنتج، والصرف — ولكلٍّ
     * مرآةٌ في المتصفّح أو عقدٌ في الدفتر. وهو تحويلُ سياسةٍ ماليّة لا إغلاقُ
     * ثغرة. انظر `TheDisplayedAmountIsTheCollectableAmountTest`.
     *
     * @param  array<string, mixed>  $currency
     */
    public static function shown(float $value, array $currency): int
    {
        $chosen = self::decimals($currency);

        // ومن اختار أربعًا يراها: منزلةٌ زائدةٌ عن التخزين تُكتب صفرًا، والصفرُ لا يكذب
        if ($chosen >= self::SCALE) {
            return $chosen;
        }

        $stored = round($value, self::SCALE);

        for ($d = $chosen; $d < self::SCALE; $d++) {
            if (abs(round($value, $d) - $stored) < 0.0005) {
                return $d;
            }
        }

        return self::SCALE;
    }

    /**
     * عددُ المنازل — من اختيار التاجر، فمن العملة، فمن منزلتين.
     *
     * @param  array<string, mixed>  $currency
     */
    public static function decimals(array $currency): int
    {
        $set = $currency['decimals'] ?? null;

        if ($set !== null && $set !== '') {
            return max(0, min(4, (int) $set));
        }

        return in_array((string) ($currency['code'] ?? ''), self::THREE, true) ? 3 : 2;
    }
}
