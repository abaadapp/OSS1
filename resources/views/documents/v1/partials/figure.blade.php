{{--
    الرقمُ الأهمّ على الورقة — بمقاس عنوان المستند، بلا صندوقٍ ولا لون.

    ═══ ولمَ يُفرَد ═══

    من يفتح ورقةً ماليّةً يسأل سؤالًا واحدًا أوّلًا: **كم؟** وهو رقمٌ كان
    يقع في آخر الورقة داخل لوحة المجاميع، بين المجموع الفرعيّ والضريبة،
    بمقاسٍ يزيد عليهما قليلًا. فيُقرأ الأربعةُ ليُعرف أيُّها المطلوب.

    وفي المرجع المعتمد يقع **قبل الجدول**، وحدَه في بياض، بمقاس العنوان.
    فيُقرأ من مسافةِ ذراع بلا أن يُصبغ شيءٌ أو يُؤطَّر.

    ═══ ولكلّ ورقةٍ رقمُها هي ═══

    الفاتورةُ رصيدُها المستحقّ، وأمرُ الشراء قيمةُ الأمر، والإشعارُ الدائن
    إجماليُّ الرصيد، وسندُ القبض المبلغُ المستلَم. فالتسميةُ معاملٌ لا
    ثابت — انظر كلَّ قالبٍ حيث يستدعيها.

    ═══ والعملةُ تُفصَل عن الرقم عرضًا لا حسابًا ═══

    `Money::format` تُخرجهما معًا — «176.400 ر.ع» — ولا تُمسّ: الحسابُ
    والمنازلُ والرمزُ كما هي. وهنا يُقسَم الناتجُ بصريًّا وحدَه ليأخذ
    الرقمُ وزنَه وتبقى العملةُ وحدةَ قياسٍ بجانبه.

    المتغيّرات: `$label` مفتاحُ التسمية · `$value` المبلغُ مصوغًا ·
    `$status` حالُ المستند إن كانت.
--}}
@php
    $money = trim((string) ($value ?? ''));

    /*
        والرقمُ ما بين أوّل خانةٍ وآخرها، وما عداه عملة.

        والصياغةُ وجهان: «176.400 ر.ع» و«ر.ع 176.400» — يختار التاجر
        موضعَ الرمز في إعدادات العملة. فيُلتمس الرقمُ حيث وقع.
    */
    preg_match('/[\d][\d.,]*/u', $money, $hit);
    $number = $hit[0] ?? $money;
    $currency = trim(str_replace($number, '', $money));

    [$first, $second] = \App\Support\Paper::pair($label ?? 'الإجمالي');
    $stamp = trim((string) ($status ?? ''));
@endphp

