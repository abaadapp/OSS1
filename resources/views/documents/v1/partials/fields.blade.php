{{--
    حقولٌ في لغتين — تسميةٌ فوق تسميةٍ فوق قيمة.

    ═══ وهي أصغرُ ما في الورقة، ومنها تُبنى ═══

    الترويسةُ وحقولُ المستند وهويّةُ المُصدِر والرقمُ الكبير: كلُّها هذه
    الجزئيّةُ مكرّرةً. فلو تغيّر إيقاعُ الحقل تغيّرت الورقةُ كلُّها معًا،
    ولا يبقى موضعٌ نُسي.

    ═══ ولمَ صفٌّ لكلّ سطرٍ لا ثلاثُ كتل ═══

    قِيس في الـPDF: mpdf يُسقط هوامشَ كتل الـ`div` وحشوَها داخل خليّة
    جدول، فتتراكم الأسطرُ ويركب بعضُها على بعض. وحشوُ خليّة الجدول
    يُحترم كاملًا — فما لا يُضبط بكتلةٍ يُضبط بصفّ.

    والفراغُ بين حقلٍ وآخر حشوٌ أسفلَ **القيمة** لا هامشٌ فوق التسمية:
    الهامشُ يسقط، والحشوُ يبقى.

    المتغيّرات:
      `$fields` قائمةُ `['label' => مفتاحٌ عربيّ, 'value' => ...]`
      `$align`  `'start'` (الافتراض) أو `'end'` للعمود المقابل
--}}
@php
    $rows = array_values(array_filter($fields ?? [], fn ($f) => filled($f['value'] ?? null)));
    $end = ($align ?? 'start') === 'end';
@endphp

@if (count($rows) > 0)
    <table class="fields{{ $end ? ' fieldsend' : '' }}">
        @foreach ($rows as $field)
            @php([$first, $second] = \App\Support\Paper::pair($field['label']))
            <tr><td class="lbl" dir="{{ \App\Support\Paper::dirOf($first, 'ltr') }}">{{ $first }}</td></tr>
            @if ($second !== '')
                {{--
                    والتسميةُ الثانية تحمل اتّجاهَها هي.

                    «.Invoice no» — نقطتُها تخرج إلى أوّل السطر في ورقةٍ
                    عربيّة: النقطةُ محايدةٌ فتتبع اتّجاهَ الفقرة لا الكلمة.
                    وهي تسميةٌ بلغةٍ واحدةٍ معلومة، فيُكتب اتّجاهُها.
                --}}
                <tr><td class="lbl2" dir="{{ \App\Support\Paper::dirOf($second, 'ltr') }}">{{ $second }}</td></tr>
            @endif
            {{--
                واتّجاهُ القيمة من لغتها، ومحاذاتُها من العمود.

                اسمُ مورّدٍ إنجليزيٍّ في ورقةٍ عربيّة — أو العكس — تنقلب
                علاماتُ ترقيمه. و`dir="auto"` لا يحلّها: mpdf لا يعرفه.
                انظر `Paper::dirOf`.
            --}}
            <tr><td class="val{{ $loop->last ? '' : ' f-end' }}"
                    dir="{{ \App\Support\Paper::dirOf((string) $field['value'], 'ltr') }}">{{ $field['value'] }}</td></tr>
        @endforeach
    </table>
@endif
