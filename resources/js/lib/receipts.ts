/**
 * الاستلامُ بلغة ما يُستلم — البضاعةُ تصل، والخدمةُ تُنفَّذ.
 *
 * المستندُ الداخليّ واحد: ورقةُ الاستلام واعتمادُها، وبها تصلح مطابقةُ سند
 * المورّد. لكنّ خدمةً (تصويرًا أو نقلًا أو أمنًا) لا «تصل الرفّ» ولا تدخل
 * المخزون — فتُسمّى «تأكيدَ تنفيذ». والنمطُ يأتي من الخادم
 * (`GoodsReceipts::mode`) أو يُحسب هنا من أنواع البنود بالقاعدة نفسِها.
 */
export type ReceiptMode = 'goods' | 'services' | 'mixed';

/** من أنواع البنود — بلا نوعٍ يُقرأ منتجًا، كما يقرؤه الخادم */
export function receiptMode(kinds: ReadonlyArray<string | null | undefined>): ReceiptMode {
    const services = kinds.filter((k) => k === 'service').length;
    if (services === 0) return 'goods';
    return services === kinds.length ? 'services' : 'mixed';
}

