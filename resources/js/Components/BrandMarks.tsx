/**
 * شعاراتُ الأدوات المربوطة — مرسومةً هنا لا مرفوعةً ملفّاتٍ.
 *
 * والشعارُ الحقيقيّ يُعرف قبل أن يُقرأ اسمُه: صفٌّ من بطاقاتٍ تحمل أيقوناتٍ
 * عامّة (دبّوسٌ رماديّ لخرائط Google وفقاعةُ محادثةٍ لواتساب) يجعل التاجر
 * يقرأ كلَّ عنوانٍ ليعرف أيَّ أداةٍ أمامه.
 *
 * وهي في الكود لا في `public/`: ملفٌّ يُرفع يحتاج مسارًا ونسخةً وكاشًا،
 * وينكسر بصمتٍ إن نُقل — والصورة المكسورة في بطاقةٍ تبدو عطبًا في النظام.
 * ونفسُ الحجّة في `renderer/icons.tsx`.
 *
 * ولا تُبدَّل ألوانُها ولا تُقصّ: هي علاماتٌ تجاريّة لأصحابها، تُعرض كما
 * هي للدلالة على الأداة — والمسّ بها يجعلها شيئًا آخر يشبهها.
 */

type MarkProps = Omit<SVGProps<SVGSVGElement>, 'viewBox'> & { size?: number };

/** إطارُ الشعار — مربّعٌ واحد لكلّها، فلا تختلف قياساتُها في الصفّ */
function Mark({ size = 48, title, children, ...rest }: MarkProps & { title: string }) {
    return (
        <svg
            width={size}
            height={size}
            viewBox="0 0 90 90"
            role="img"
            aria-label={title}
            focusable="false"
            {...rest}
        >
            {children}
        </svg>
    );
}

