/**
 * أداةٌ لا شعارَ لها بعد — حرفُها الأوّل على مربّعٍ بلونها.
 *
 * وهذا ليس شعارًا يُنسب إلى أحد: رسمُ علامةٍ تجاريّة من الذاكرة يُنتج شيئًا
 * يشبهها ولا هو هي، فيُعرض على أنّه هي. والحرفُ يقول «هذه الأداة» ولا
 * يدّعي أنّه علامتُها.
 */
export function LetterMark({ letter, tint, size = 48, ...rest }: MarkProps & { letter: string; tint: string }) {
    return (
        <svg
            width={size}
            height={size}
            viewBox="0 0 90 90"
            role="img"
            aria-hidden="true"
            focusable="false"
            {...rest}
        >
            <rect width="90" height="90" rx="20" fill={tint} opacity="0.12" />
            <text
                x="45"
                y="46"
                textAnchor="middle"
                dominantBaseline="central"
                fill={tint}
                fontSize="42"
                fontWeight="700"
                fontFamily="system-ui, sans-serif"
            >
                {letter}
            </text>
        </svg>
    );
}

/**
 * شعارُ الأداة بمفتاحها — مصدرٌ واحد تقرأ منه البطاقةُ والشاشة.
 *
 * ولولاه لاختار كلُّ موضعٍ شعارَه: البطاقةُ في اللوحة تعرض شعار واتساب،
 * وبابُ الأداة يعرض فقاعةَ محادثةٍ خضراء — فيشكّ من ضغط البطاقة أنّه وصل
 * إلى غير ما ضغط.
 */
export function ToolMark({
    tool,
    name,
    tint,
    size = 48,
    ...rest
}: MarkProps & { tool: string; name?: string; tint?: string }) {
    if (tool === 'google') {
        return <GoogleMapsMark size={size} {...rest} />;
    }

    if (tool === 'whatsapp') {
        return <WhatsAppBusinessMark size={size} {...rest} />;
    }

    // وما لا شعارَ له يأخذ حرفَه الأوّل — ولا يُنسب إليه ما ليس له
    return (
        <LetterMark
            letter={(name ?? tool).slice(0, 1).toUpperCase()}
            tint={tint ?? '#6b7280'}
            size={size}
            {...rest}
        />
    );
}
