/**
 * أيّ متجرٍ هذا؟ — من ترويسة الطلب، بحذر.
 *
 * `Host` نصٌّ يرسله العميل، لا حقيقةٌ يضمنها الخادم. ويُستعمل هنا في بناء
 * مسارٍ يُطلب من افنت بلس وفي بناء الروابط الأساسية — فلو مُرّر كما وصل لأمكن
 * حقنُ مسارٍ فيه (`../`) أو نطاقٍ في الوسوم. فيُقصّ ويُتحقّق منه، وما لم
 * يُطابق شكلَ نطاقٍ يُردّ null ويرى الزائر صفحة «لا موقع هنا».
 */

const SHAPE = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

export function normalizeHost(raw: string | null | undefined): string | null {
    if (!raw) return null;

    let host = raw.trim().toLowerCase();

    // ترويسةٌ فيها أكثر من مضيف (خلف وكيلٍ مُساء ضبطُه) — الأوّل هو الطلب
    host = host.split(',')[0].trim();
    // المنفذ ليس من النطاق، والنقطة الأخيرة صيغةٌ مطلقة تعني النطاق نفسه
    host = host.replace(/:\d+$/, '').replace(/\.$/, '');

    if (host.startsWith('www.')) {
        host = host.slice(4);
    }

    if (host.length < 3 || host.length > 255 || !SHAPE.test(host)) {
        return null;
    }

    return host;
}

/**
 * أصلُ الموقع كما يراه الزائر — لأجل الروابط المطلقة في الوسوم وsitemap.
 *
 * وhttps دائمًا، ولا يُقرأ ما يقوله الوكيل.
 *
 * كان يُقرأ من `x-forwarded-proto`، وهذا يبدو صوابًا حتى يُنسى ضبطُ الترويسة
 * في nginx مرّةً واحدة: فيصير Next يملؤها من الاتّصال الداخليّ (`http`)،
 * فتخرج كلّ الروابط القانونيّة بـ`http` — ويرى غوغل نسختين من كلّ صفحة
 * ويقسم ترتيبَها بينهما. ولا أحد يلاحظ، لأنّ الموقع يعمل.
 *
 * ونطاقُ كلّ تاجر له شهادته (انظر `docs/DEPLOY.md`)، فلا حالةَ صحيحةٌ يخرج
 * فيها رابطٌ قانونيّ بـhttp.
 */
export function siteOrigin(host: string): string {
    return `https://${host}`;
}
