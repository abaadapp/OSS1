<?php

use Illuminate\Database\Migrations\Migration;
use Illuminate\Support\Facades\Storage;

/**
 * المرفقاتُ القديمة تنتقل خلف الباب.
 *
 * ═══ ما كان ═══
 *
 * فواتيرُ المصروفات وإيصالاتُ دفع أوامر الشراء كانت على القرص العامّ منذ
 * أوّل يوم. و`public/storage` وصلةٌ يخدمها الخادمُ مباشرةً: لا Laravel
 * يُستدعى ولا جلسةَ يُسأل عنها — من عرف المسار قرأ الملفّ، مسجّلًا كان أو
 * غير مسجّل، من هذا المتجر أو من غيره.
 *
 * ═══ ولماذا هجرةٌ لا أمرُ صيانة ═══
 *
 * لأنّ الكودَ بعد هذا الإصدار يكتب على القرص الخاصّ ويقرأ منه. فلو تُرك
 * النقلُ لأمرٍ يُشغَّل باليد، لكانت بين النشر وتشغيله نافذةٌ يقرأ فيها
 * الكودُ من مكانٍ والملفّاتُ في غيره: كلُّ مرفقٍ قديمٍ يُردّ ٤٠٤. وأمرٌ
 * يُنسى أسوأ: عطبٌ صامتٌ لا يشتكي منه أحدٌ حتى يُطلب إيصالٌ في تدقيق.
 *
 * ═══ وما لا يُنقل ═══
 *
 * صورُ المنتجات وشعاراتُ المتاجر وصورُ الموظفين وملفّاتُ الموقع تبقى
 * عامّةً: واجهةُ المتجر تعرضها لزوّارٍ لا حساب لهم، ونقلُها خلف بابٍ يسأل
 * عن الجلسة يُطفئ صورَ المتجر على الإنترنت.
 *
 * والمسارُ نفسُه لا يتغيّر — `expenses/1/x.pdf` كما هو — يتبدّل جذرُه
 * وحده. فلا صفَّ يُعاد كتابته، ولا رقمَ يُخمَّن.
 */
return new class extends Migration
{
    /** مجلّداتُ المستندات المالية على القرص العامّ */
    private const FOLDERS = ['expenses', 'purchase-receipts'];

    public function up(): void
    {
        $this->move('public', 'local');
    }

    /** والتراجعُ يعيدها كما كانت — وإلّا صار الرجوعُ عن الإصدار فقدًا للملفّات */
    public function down(): void
    {
        $this->move('local', 'public');
    }

    /**
     * نقلٌ ملفًّا ملفًّا، ولا يُحذف الأصلُ قبل أن تثبت النسخة.
     *
     * و`Storage::move` بين قرصين لا يعمل — القرصان جذران مختلفان لنظام
     * الملفّات نفسه، فالنقلُ قراءةٌ ثمّ كتابةٌ ثمّ حذف.
     */
    private function move(string $from, string $to): void
    {
        $source = Storage::disk($from);
        $target = Storage::disk($to);

        foreach (self::FOLDERS as $folder) {
            foreach ($source->allFiles($folder) as $path) {
                /*
                 * وما وصل قبلَنا لا يُكتب فوقه.
                 *
                 * الهجرةُ قد تُعاد على نسخةٍ نُقلت نصفَها، وملفٌّ في الوجهة
                 * هو الملفُّ نفسه بالمسار نفسه.
                 */
                if (! $target->exists($path)) {
                    $stream = $source->readStream($path);

                    if ($stream === null) {
                        continue;
                    }

                    $target->writeStream($path, $stream);

                    if (is_resource($stream)) {
                        fclose($stream);
                    }
                }

                // ولا يُحذف الأصلُ إلّا بعد أن تثبت النسخة على الجانب الآخر
                if ($target->exists($path)) {
                    $source->delete($path);
                }
            }
        }
    }
};
